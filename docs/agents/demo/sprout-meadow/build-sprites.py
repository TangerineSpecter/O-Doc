"""Encode existing bestiary art as 128px indexed sprites, like MonsterTemplate_v1.

Run with .venv/bin/python docs/agents/demo/sprout-meadow/build-sprites.py.
Writes the demo and observation's generated sprite data; source artwork is read-only.
"""
import base64
import json
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
ASSETS = ROOT / "frontend_react/src/assets/combat"
SOURCES = {
    "rabbit": ("monster-fuzzy-ear-rabbit-v1.png", 1),
    "beetle": ("monster-leafshell-beetle-v1.png", -1),
    "glowbug": ("monster-dawnfire-glowbug-v1.png", -1),
}


def encode_sprite(filename: str, facing: int) -> dict:
    source = Image.open(ASSETS / filename).convert("RGBA")
    bounds = source.getchannel("A").point(lambda value: 255 if value > 127 else 0).getbbox()
    if bounds is None:
        raise ValueError(f"Empty sprite: {filename}")
    source = source.crop(bounds)
    scale = min(120 / source.width, 116 / source.height)
    size = (round(source.width * scale), round(source.height * scale))
    source = source.resize(size, Image.Resampling.NEAREST)
    canvas = Image.new("RGBA", (128, 128))
    offset = ((128 - size[0]) // 2, 119 - size[1])
    canvas.paste(source, offset)
    # Quantize occupied pixels only, so transparency does not consume color slots.
    rgba = list(canvas.get_flattened_data())
    occupied = [pixel[:3] for pixel in rgba if pixel[3] >= 128]
    strip = Image.new("RGB", (len(occupied), 1))
    strip.putdata(occupied)
    quantized = strip.quantize(colors=64, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    raw_palette = quantized.getpalette()
    palette = ["#%02x%02x%02x" % tuple(raw_palette[n:n + 3]) for n in range(0, 64 * 3, 3)]
    indices = iter(quantized.get_flattened_data())
    pixels = bytes(next(indices) + 1 if pixel[3] >= 128 else 0 for pixel in rgba)
    return {"source": str((ASSETS / filename).relative_to(ROOT)), "sourceFacing": facing,
            "width": 128, "height": 128, "palette": palette,
            "pixels": base64.b64encode(pixels).decode("ascii")}


if __name__ == "__main__":
    data = {key: encode_sprite(*source) for key, source in SOURCES.items()}
    target = HERE / "sprite-data.js"
    target.write_text("/* Generated by build-sprites.py from existing bestiary artwork. */\n"
                      "window.MeadowSpriteData = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    observation = ROOT / "frontend_react/src/components/Combat/animation/meadowPixels/meadowSpriteData.ts"
    observation.write_text("/* Generated by docs/agents/demo/sprout-meadow/build-sprites.py. */\n"
                           "import type {IndexedSprite, MeadowKey} from './meadowTypes';\n"
                           "export const meadowSpriteData: Record<Exclude<MeadowKey, 'slime'>, IndexedSprite> = "
                           + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"Encoded {len(data)} detailed 128x128 sprites: {target.relative_to(ROOT)}")
    print(f"Observation data: {observation.relative_to(ROOT)}")
