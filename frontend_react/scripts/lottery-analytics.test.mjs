import assert from 'node:assert/strict';
import {after, test} from 'node:test';
import {setupServer} from 'msw/node';
import {localHandlers, unhandledLocalApi} from '../src/mocks/local.ts';
import {analytics} from '../src/mocks/agentWorld/social.ts';
import {day} from '../src/mocks/agentWorld/residents.ts';
const location = new URL('http://localhost/?mockState=populated');
const previous = Object.getOwnPropertyDescriptor(globalThis, 'location');
Object.defineProperty(globalThis, 'location', {value: location, configurable: true});
const server = setupServer(...localHandlers, unhandledLocalApi);
server.listen({onUnhandledRequest: 'error'});
after(() => {server.close(); if (previous) Object.defineProperty(globalThis, 'location', previous); else Reflect.deleteProperty(globalThis, 'location');});
const get = async (query = '') => {
    const response = await fetch(`http://localhost/api/settings/agent-world/analytics/?start_date=${day}&end_date=${day}&${query}`);
    return {status: response.status, ...(await response.json())};
};
test('lottery counts distinguish shared rounds, repeated winning tickets and actual prizes', async () => {
    const {data, status} = await get();
    assert.equal(status, 200);
    const {overview, residents} = data.lotteryStatistics;
    assert.equal(overview.rounds, 2);
    assert.equal(overview.tickets, residents.reduce((sum, row) => sum + row.tickets, 0));
    assert.equal(overview.secondTickets, 8);
    assert.equal(overview.secondAwards, 4);
    assert.equal(overview.secondPrize, '200.00');
    assert.equal(overview.prizes, '460.00');
    assert.equal(overview.expense, '100.00');
    assert.equal(overview.net, '360.00');
    assert.equal(overview.maxPrize, '180.00');
    assert.equal(overview.winRate, 81.3);
});
test('resident and date filters, empty, loading and errors are handled locally', async () => {
    const selected = await get(`actor_id=${analytics.residents[1].id}`);
    assert.equal(selected.data.lotteryStatistics.residents.length, 1);
    assert.equal(selected.data.lotteryStatistics.overview.secondAwards, 1);
    const outside = await fetch('http://localhost/api/settings/agent-world/analytics/?start_date=2000-01-01&end_date=2000-01-01');
    const outsideData = (await outside.json()).data.lotteryStatistics.overview;
    assert.equal(outsideData.tickets, 0);
    assert.equal(outsideData.net, '0.00');
    assert.equal(outsideData.winRate, null);
    location.search = '?mockState=empty';
    const empty = (await get()).data.lotteryStatistics;
    assert.deepEqual(empty.residents, []);
    assert.equal(empty.overview.tickets, 0);
    assert.equal(empty.overview.prizes, '0.00');
    location.search = '?mockState=slow';
    const started = performance.now();
    assert.equal((await get()).status, 200);
    assert.ok(performance.now() - started >= 1700);
    location.search = '?mockState=error';
    assert.equal((await get()).status, 503);
    location.search = '?mockState=populated';
});
