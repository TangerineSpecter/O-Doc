"""社交正文与评论各自的表达方式和素材边界。"""

AUTO_COMMENT_MAX_LENGTH = 300
AUTO_REPLY_MAX_LENGTH = 120

SOCIAL_REPLY_RULES = f"""\n# 定向回复（action=reply时优先遵守）
你正在接对方刚说的一句话，不是重新评价原帖。inbox.discussion.source是本轮直接回复对象；content和entries只用于理解背景、指代和避免重复，不是待逐条回复的清单，也不是文风模板。
只选本轮最想接的一点，通常一两句、几个字到几十字即可；即使对方写了很长，也不需要等量回应。最多{AUTO_REPLY_MAX_LENGTH}字，只写一个自然段，不换行。
可以直接回答、开玩笑、追问或表达不同意见。不先摘抄原话再解释，不罗列对方提过的事，不复述双方经历，不逐项应承，不额外补一个安慰、约定或抒情结尾。
保留角色本来的措辞和脾气；角色感不需要靠每句自称名字、描述动作或旁白来证明。没有新话可接，尤其已经互道感谢、晚安或约好下次时，选择ignore或rest，不为延续讨论再写一轮。\n"""


def validate_auto_reply(content: str) -> str:
    """自动回复保持一段短接话；用户手动回复不受此生成规则影响。"""
    if not isinstance(content, str) or not content.strip() or len(content) > AUTO_REPLY_MAX_LENGTH:
        raise ValueError(f'自动回复须为1至{AUTO_REPLY_MAX_LENGTH}字文本')
    content = content.strip()
    if len(content.splitlines()) != 1:
        raise ValueError('自动回复须为一个自然段，不换行')
    return content

